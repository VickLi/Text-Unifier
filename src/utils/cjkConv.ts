/**
 * 繁体→简体
 */
export function toSimplified(text: string): string {
  let result = '';
  for (const ch of text) {
    result += T2S[ch] || ch;
  }
  return result;
}

/**
 * 简体→繁体（反向映射）
 */
export function toTraditional(text: string): string {
  const s2t: Record<string, string> = {};
  for (const [t, s] of Object.entries(T2S)) {
    if (!s2t[s]) s2t[s] = t;
  }
  let result = '';
  for (const ch of text) {
    result += s2t[ch] || ch;
  }
  return result;
}
